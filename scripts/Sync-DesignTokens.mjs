// Regenerates src/PbiAssure.Reporting/DesignSystem.cs from the two stylesheets that own the
// PBI Assure design system.
//
//   src/PbiAssure.Web/wwwroot/css/core.css        design tokens and shared primitives
//   src/PbiAssure.Reporting/Styles/report.css     the generated report's presentation layer
//
// The browser application links those files directly. The generated HTML report is a single
// self-contained file, so it needs the same CSS as compiled string constants. Run this script
// after editing either stylesheet; DesignSystemSourceTests fails when the copies drift.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const coreCssPath = join(repositoryRoot, "src", "PbiAssure.Web", "wwwroot", "css", "core.css");
const reportCssPath = join(repositoryRoot, "src", "PbiAssure.Reporting", "Styles", "report.css");
const generatedPath = join(repositoryRoot, "src", "PbiAssure.Reporting", "DesignSystem.cs");

const core = readStylesheet(coreCssPath);
const report = readStylesheet(reportCssPath);

writeFileSync(generatedPath, renderDesignSystem(core, report), "utf8");
console.log(`Regenerated ${generatedPath} from core.css (${core.length} chars) and report.css (${report.length} chars).`);

function readStylesheet(path) {
    const content = readFileSync(path, "utf8").replaceAll("\r\n", "\n").trimEnd();
    if (content.includes('"""')) {
        throw new Error(`${path} contains a raw string literal terminator and cannot be embedded.`);
    }

    return content;
}

function renderDesignSystem(coreCss, reportCss) {
    return `// <auto-generated>
// Generated by scripts/Sync-DesignTokens.mjs. Do not edit by hand.
// Edit src/PbiAssure.Web/wwwroot/css/core.css or src/PbiAssure.Reporting/Styles/report.css
// and run: node scripts/Sync-DesignTokens.mjs
// </auto-generated>

namespace PbiAssure.Reporting;

/// <summary>
/// The PBI Assure design system as compiled text.
///
/// The browser application links these stylesheets as files. A generated report has to travel as
/// one self-contained document, so the same bytes are inlined into its head. Keeping a single
/// source for both is what stops the two surfaces drifting into different products.
/// </summary>
public static class DesignSystem
{
    /// <summary>Design tokens and the primitives shared with the browser application.</summary>
    public const string Core = ${asRawStringLiteral(coreCss)};

    /// <summary>Presentation for the generated report, layered on top of <see cref="Core"/>.</summary>
    public const string Report = ${asRawStringLiteral(reportCss)};
}
`;
}

function asRawStringLiteral(content) {
    const body = content
        .split("\n")
        .map(line => (line.trim().length === 0 ? "" : `        ${line}`))
        .join("\n");

    return `"""\n${body}\n        """`;
}
